#!/usr/bin/env python3
"""The Android language picker, generated from the core's one list of offered languages.

`AppLanguageCatalog` in `Packages/StrandCore` declares which languages the app offers. The Apple
picker and the coach are held to it by tests; this writes the Android enum from it, so the Android
list cannot drift the way it had by 2026-11-22: Russian was translated on Android down to the core's
own table and the picker did not offer it, while Chinese carried a different autonym than on Apple.

Which languages Android can actually show is NOT declared anywhere. It is read from the tree: a
language is emitted when `res/values-<qualifier>/strings.xml` exists, English being `values/`. So a
new translation reaches the picker by running this, and a language the catalogue offers while Android
has no strings for it is listed in the generated file as left out, rather than silently offered and
then shown in the wrong language.

    python3 Tools/gen_app_languages.py           # regenerate the Kotlin enum
    python3 Tools/gen_app_languages.py --check   # exit 1 when it no longer matches the catalogue

Nothing on the Apple side is generated, so no language the iPhone offers can change through this.
"""

from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CATALOG = ROOT / "Packages/StrandCore/Sources/StrandCore/AppLanguageCatalog.swift"
KOTLIN = ROOT / "android/app/src/main/java/com/noop/ui/AppLanguage.kt"
RES = ROOT / "android/app/src/main/res"

BEGIN = "    // BEGIN generated by Tools/gen_app_languages.py — edit AppLanguageCatalog.swift instead"
END = "    // END generated"

ENTRY = re.compile(
    r'\.init\(tag:\s*"([^"]+)",\s*autonym:\s*"([^"]+)",\s*englishName:\s*"([^"]+)",\s*'
    r'androidQualifier:\s*(?:"([^"]+)"|nil)\)',
    re.S,
)


class Language:
    def __init__(self, tag: str, autonym: str, english: str, qualifier: str | None):
        self.tag = tag
        self.autonym = autonym
        self.english = english
        self.qualifier = qualifier

    @property
    def case_name(self) -> str:
        """The Kotlin case: the English name, upper snake case, without its parenthetical."""
        base = self.english.split("(")[0].strip()
        if "(" in self.english:
            base = f"{base} {self.english.split('(')[1].rstrip(')')}"
        return re.sub(r"[^A-Z0-9]+", "_", base.upper()).strip("_")

    @property
    def strings_file(self) -> pathlib.Path:
        return RES / ("values" if self.qualifier is None else f"values-{self.qualifier}") / "strings.xml"


def catalog() -> list[Language]:
    text = CATALOG.read_text(encoding="utf-8")
    found = [Language(tag, autonym, english, qualifier or None)
             for tag, autonym, english, qualifier in ENTRY.findall(text)]
    if not found:
        sys.exit(f"no languages found in {CATALOG}; the catalogue's shape changed")
    return found


def android_locales() -> set[str]:
    """Every translated locale in the tree, by its resource qualifier."""
    return {d.name[len("values-"):] for d in RES.glob("values-*") if (d / "strings.xml").is_file()}


def render(languages: list[Language]) -> tuple[str, list[Language]]:
    have = android_locales()
    offered = [l for l in languages if l.qualifier is None or l.qualifier in have]
    missing = [l for l in languages if l not in offered]

    lines = [BEGIN]
    lines.append("    SYSTEM(null, \"\"),")
    for index, language in enumerate(offered):
        tail = ";" if index == len(offered) - 1 else ","
        lines.append(f'    {language.case_name}("{language.tag}", "{language.autonym}"){tail}')
    if missing:
        lines.append("")
        lines.append("    // Offered on Apple and left out here for want of a translation:")
        for language in missing:
            lines.append(f"    //   {language.tag} ({language.english}) needs"
                         f" res/values-{language.qualifier}/strings.xml")
    lines.append(END)
    return "\n".join(lines), missing


def main() -> int:
    check = "--check" in sys.argv[1:]
    languages = catalog()

    # The gap that had Russian translated and unofferable: a locale in the tree that the catalogue
    # does not know is not a language anybody can pick, and nothing else would ever say so.
    known = {l.qualifier for l in languages if l.qualifier}
    orphans = sorted(android_locales() - known)
    if orphans:
        print(f"res/values-{{{','.join(orphans)}}} is translated and not in AppLanguageCatalog: "
              "nobody can pick it", file=sys.stderr)
        return 1

    block, missing = render(languages)
    current = KOTLIN.read_text(encoding="utf-8")
    if BEGIN not in current or END not in current:
        print(f"{KOTLIN} has no generated block; add the BEGIN/END markers once", file=sys.stderr)
        return 1
    head, rest = current.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    updated = head + block + tail

    if updated == current:
        print(f"OK {len(languages) - len(missing)} languages, matching the catalogue")
        return 0
    if check:
        print(f"{KOTLIN} no longer matches AppLanguageCatalog; run Tools/gen_app_languages.py",
              file=sys.stderr)
        return 1
    KOTLIN.write_text(updated, encoding="utf-8")
    print(f"wrote {KOTLIN} ({len(languages) - len(missing)} languages"
          + (f", {len(missing)} awaiting a translation)" if missing else ")"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
